"""An explicit allowlist for throwaway chats and durable created descendants."""
from __future__ import annotations

import hashlib
import json
import os
from pathlib import Path
import re
import stat

from ...domain.errors import NotAvailable

_ID = re.compile(r'^[A-Za-z0-9_-]+$')


class ChatScope:
    """Keep native content access bounded to an explicitly supplied set of IDs."""

    def __init__(self, root: Path, allowed_ids=()):
        self.root = root
        self.original = frozenset(allowed_ids)
        if any(not isinstance(ident, str) or not _ID.fullmatch(ident) for ident in self.original):
            raise ValueError('chat_scope')
        self.created: set[str] = set()
        self.key = hashlib.sha256(json.dumps(sorted(self.original)).encode()).hexdigest()[:24]
        folder = root / '.baton-rollback'
        if folder.exists() and not folder.is_symlink():
            directory = folder.lstat()
            if directory.st_uid != os.getuid() or stat.S_IMODE(directory.st_mode) != 0o700:
                return
            for intent in folder.glob(self.key + '-*.json'):
                try:
                    info = intent.lstat()
                    if (not stat.S_ISREG(info.st_mode) or info.st_uid != os.getuid() or
                            stat.S_IMODE(info.st_mode) != 0o600 or info.st_nlink != 1):
                        continue
                    descriptor = os.open(intent, os.O_RDONLY | os.O_NOFOLLOW)
                    with os.fdopen(descriptor) as stream:
                        self.recover_created(json.load(stream), intent)
                except (OSError, ValueError, KeyError, TypeError, NotAvailable):
                    continue

    def checked_path(self, path: Path) -> Path:
        """Refuse symlink intermediates and non-owned or multiply-linked files."""
        path = Path(path).absolute()
        if not path.is_relative_to(self.root) or '..' in path.relative_to(self.root).parts:
            raise NotAvailable()
        current = self.root
        for part in path.relative_to(self.root).parts:
            current = current / part
            try:
                info = current.lstat()
            except FileNotFoundError:
                continue
            if (stat.S_ISLNK(info.st_mode) or info.st_uid != os.getuid() or
                    (not stat.S_ISDIR(info.st_mode) and
                     (not stat.S_ISREG(info.st_mode) or info.st_nlink != 1))):
                raise NotAvailable()
        return path

    def require(self, ident: str) -> None:
        """Refuse an ID outside the original scope or verified created descendants."""
        if ident not in self.original and ident not in self.created:
            raise NotAvailable()

    def contains(self, ident: str) -> bool:
        """Whether this adapter may access the native content of this ID."""
        return ident in self.original or ident in self.created

    def register_created(self, ident: str) -> None:
        """Register an ID generated by a prepared create inside this adapter."""
        if not _ID.fullmatch(ident):
            raise ValueError('chat_id')
        self.created.add(ident)

    def recover_created(self, manifest: dict, intent: Path) -> None:
        """Authorize a descendant only from the private, matching original intent."""
        info = intent.lstat()
        if (not stat.S_ISREG(info.st_mode) or info.st_uid != os.getuid() or
                stat.S_IMODE(info.st_mode) != 0o600 or info.st_nlink != 1 or
                manifest.get('scope') != sorted(self.original) or manifest.get('kind') != 'create'):
            raise NotAvailable()
        ident = manifest['chat_id']
        expected = self.root / '.codex' / 'sessions'
        rollout = Path(manifest['rollout']['path'])
        if (not rollout.resolve().is_relative_to(expected.resolve()) or
                not rollout.name.endswith('-' + ident + '.jsonl')):
            raise NotAvailable()
        self.register_created(ident)
