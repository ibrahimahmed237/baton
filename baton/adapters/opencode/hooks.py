"""Generate and install a rooted OpenCode plugin without claiming it has loaded."""
import json
import os
import tempfile
from pathlib import Path

from ...notes.catalogue import get

from ...domain.errors import NotAvailable
from ...ports.tool import SetupFinding


class OpenCodeHooks:
    """Plugin installation and readiness remain separate observations."""
    global_location_verified = False
    install_requires_closed_app = False

    def install_project(self, path):
        from pathlib import Path
        return str(Path(path).parents[2])

    def install_path(self, scope, project):
        from pathlib import Path
        return Path(project) / '.opencode/plugins/baton.js' if scope == 'project' else self.adapter.root / '.config/opencode/plugins/baton.js'


    COMMANDS = ("catch-up", "notify")

    install_next_note = 'setup.restart_once'

    def install_entries(self, executable):
        previous = self.executable
        try:
            self.executable = executable
            return self.plugin_content()
        finally:
            self.executable = previous

    def use_install_path(self, path):
        path = Path(path)
        self._install_path = path
        if path.parts[-3:] != ('.opencode', 'plugins', 'baton.js'):
            raise NotAvailable()
        self.plugin_folder = path.parents[2]
        self.plugin_locator = type(self.adapter.locator)(self.plugin_folder)

    def use_installed_command(self, executable):
        self.executable = executable

    def __init__(self, adapter, entrypoints_available=None, loaded=None, executable="baton", plugin_folder=None):
        self.adapter = adapter
        self.entrypoints_available = entrypoints_available or (lambda: False)
        self.loaded = loaded or (lambda: False)
        self.executable = str(adapter.root / ".local/bin/baton") if executable == "baton" else executable
        folder = Path(plugin_folder).absolute() if plugin_folder is not None else adapter.root
        self.plugin_locator = type(adapter.locator)(folder)
        self.plugin_folder = folder

    @property
    def path(self):
        """Install per project folder, as measured by the spike."""
        if hasattr(self, '_install_path'): return self._install_path
        return self.plugin_locator.inside(self.plugin_folder / ".opencode/plugins/baton.js")

    def plugin_content(self):
        """Generate synthetic prompt context and busy/idle notifications with stable IDs."""
        template = Path(__file__).parents[2] / 'hooks/opencode_plugin.js'
        return template.read_text().replace('__BATON_FAILURE_NOTE__', json.dumps(get('hooks.command_failed').template)).replace('execFile("baton",', 'execFile(' + json.dumps(self.executable) + ',')

    def check(self):
        """Report file installation independently from observed plugin loading."""
        installed = self.path.is_file() and self.path.read_text() == self.plugin_content()
        entrypoints = self.entrypoints_available()
        ready = installed and entrypoints and self.loaded()
        return SetupFinding("hooks", ready, "" if ready else "setup.restart_once" if installed and entrypoints else "setup.hooks",
                            {"tool": "opencode", "need": "restart_once", "installed": installed, "loaded": ready})

    def install(self):
        """Leave the folder untouched until both CLI entry points are available."""
        if not self.entrypoints_available():
            return self.check()
        if self.path.exists() and self.path.read_text() != self.plugin_content():
            raise NotAvailable()
        self.path.parent.mkdir(parents=True, exist_ok=True)
        fd, temporary = tempfile.mkstemp(prefix=".baton-", dir=self.path.parent)
        try:
            with os.fdopen(fd, "w") as stream:
                stream.write(self.plugin_content())
                stream.flush()
                os.fsync(stream.fileno())
            os.replace(temporary, self.path)
        finally:
            Path(temporary).unlink(missing_ok=True)
        return self.check()

    def uninstall(self):
        """Remove only the exact plugin generated by this adapter."""
        if self.path.is_file() and self.path.read_text() == self.plugin_content():
            self.path.unlink()

    def attach_reply(self, text, notice):
        """Return ordinary context for a synthetic native text part."""
        return "\n\n".join(s for s in (notice, text) if s)

    def turn_end_reply(self):
        """No plugin response is required for a completed reply."""
        return ""
